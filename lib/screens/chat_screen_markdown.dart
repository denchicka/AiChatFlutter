/// Извлекает все LaTeX формулы из входной строки
///
/// Ищет формулы в различных форматах:
/// - $$...$$ (блочные формулы)
/// - \[...\] (блочные формулы LaTeX)
/// - \(...\) (инлайн формулы LaTeX)
/// - $...$ (инлайн формулы, но не $$...$$)
/// - Эвристически определяет формулы по паттернам
///
/// [input] - входная строка с markdown и LaTeX
/// Возвращает список уникальных формул без дубликатов
List<String> extractLatexFormulas(String input) {
  // Удаляем блоки кода (```...```), чтобы не искать формулы внутри кода
  // Заменяем их на перенос строки для сохранения структуры
  final noCode = input.replaceAll(RegExp(r'```[\s\S]*?```'), '\n');

  // Список для хранения найденных формул
  final out = <String>[];
  // Множество для отслеживания уже добавленных формул (избегаем дубликатов)
  final seen = <String>{};

  /// Вспомогательная функция для добавления формулы в список
  /// [s] - строка с формулой (может быть null)
  void add(String? s) {
    // Убираем пробелы в начале и конце
    final t = (s ?? '').trim();
    // Пропускаем пустые строки
    if (t.isEmpty) return;
    // Пропускаем простые операторы сравнения (не формулы)
    if (t == '=' || t == '==' || t == '===') return;
    // Добавляем только если формула еще не встречалась
    // seen.add() возвращает true если элемент был добавлен (не существовал)
    if (seen.add(t)) out.add(t);
  }

  // Поиск блочных формул в формате $$...$$
  // Регулярное выражение: \$\$ - два знака доллара
  // ([\s\S]+?) - любое содержимое (включая переносы строк), нежадный поиск
  // \$\$ - закрывающие два знака доллара
  for (final m in RegExp(r'\$\$([\s\S]+?)\$\$').allMatches(noCode)) {
    // m.group(1) - содержимое между $$...$$
    add(m.group(1));
  }

  // Поиск блочных формул в формате \[...\]
  // \\\[ - экранированная открывающая скобка \[
  // (.+?) - содержимое формулы, нежадный поиск
  // \\\] - экранированная закрывающая скобка \]
  // dotAll: true - точка (.) также совпадает с переносами строк
  for (final m in RegExp(r'\\\[(.+?)\\\]', dotAll: true).allMatches(noCode)) {
    // m.group(1) - содержимое между \[...\]
    add(m.group(1));
  }

  // Поиск инлайн формул в формате \(...\)
  // \\\( - экранированная открывающая скобка \(
  // (.+?) - содержимое формулы
  // \\\) - экранированная закрывающая скобка \)
  for (final m in RegExp(r'\\\((.+?)\\\)', dotAll: true).allMatches(noCode)) {
    // m.group(1) - содержимое между \(...\)
    add(m.group(1));
  }

  // Поиск инлайн формул в формате $...$ (но не $$...$$)
  // \$ - экранированный знак доллара
  // ([^\$]+?) - один или более символов, не являющихся долларом, нежадный поиск
  // \$ - закрывающий знак доллара
  final reInline = RegExp(r'\$([^\$]+?)\$');
  for (final m in reInline.allMatches(noCode)) {
    // Позиция начала совпадения в строке
    final start = m.start;
    // Позиция конца совпадения в строке
    final end = m.end;

    // Проверяем, есть ли знак доллара перед найденной формулой
    // Это нужно чтобы отличить $...$ от $$...$$
    final prevDollar = start > 0 && noCode[start - 1] == r'$';
    // Проверяем, есть ли знак доллара после найденной формулы
    final nextDollar = end < noCode.length && noCode[end] == r'$';
    // Если есть доллар до или после - это часть $$...$$, пропускаем
    if (prevDollar || nextDollar) continue; // отсекаем $$...$$

    // Добавляем найденную инлайн формулу
    add(m.group(1));
  }

  // Эвристический поиск формул по паттернам в строках
  // Разбиваем текст на строки для анализа
  for (final line in noCode.split('\n')) {
    // Убираем пробелы в начале и конце строки
    final t = line.trim();
    // Пропускаем пустые строки
    if (t.isEmpty) continue;

    // Проверяем наличие знака равенства (часто встречается в формулах)
    final hasEquals = t.contains('=');
    // Проверяем наличие математических токенов:
    // r'\' - обратный слэш (LaTeX команды)
    // '^' - степень
    // '_' - индекс
    final hasMathTokens =
        t.contains(r'\') || t.contains('^') || t.contains('_');
    // Проверяем наличие букв или цифр (формула должна содержать переменные/числа)
    final hasLettersOrDigits = RegExp(r'[A-Za-zА-Яа-я0-9]').hasMatch(t);

    // Если строка содержит все признаки формулы - добавляем её
    if (hasEquals && hasMathTokens && hasLettersOrDigits) add(t);
  }

  // Возвращаем список всех найденных уникальных формул
  return out;
}

/// Преобразует Markdown текст в обычный текст без форматирования
///
/// Удаляет все markdown-разметку, оставляя только читаемый текст.
/// Используется для копирования текста в буфер обмена.
///
/// [input] - строка с markdown разметкой
/// Возвращает обычный текст без форматирования
String markdownToPlainText(String input) {
  // Копируем входную строку для обработки
  var s = input;

  // Обработка блоков кода (```...```)
  // Оставляем содержимое блока, но убираем обрамляющие ``` и название языка
  s = s.replaceAllMapped(RegExp(r'```[\s\S]*?```'), (m) {
    // Получаем весь блок кода (включая ```)
    final block = m.group(0)!;
    // Убираем открывающий ``` и название языка (если есть)
    // ^```[^\n]*\n - начало строки, три обратных кавычки, любые символы кроме переноса, перенос
    return block
        .replaceFirst(RegExp(r'^```[^\n]*\n'), '')
        // Убираем закрывающий ```
        // \n```$ - перенос строки, три обратных кавычки, конец строки
        .replaceFirst(RegExp(r'\n```$'), '');
  });

  // Удаляем инлайн код (обратные кавычки `код`)
  // Просто убираем все обратные кавычки
  s = s.replaceAll('`', '');

  // Преобразование ссылок [текст](url) -> текст (url)
  // \[ - экранированная открывающая скобка
  // ([^\]]+) - текст ссылки (один или более символов кроме ])
  // \] - закрывающая скобка
  // \( - экранированная открывающая скобка для URL
  // ([^)]+) - URL (один или более символов кроме ))
  // \) - закрывающая скобка
  s = s.replaceAllMapped(RegExp(r'\[([^\]]+)\]\(([^)]+)\)'), (m) {
    // Текст ссылки (первая группа)
    final text = m.group(1) ?? '';
    // URL ссылки (вторая группа)
    final url = m.group(2) ?? '';
    // Если URL пустой, возвращаем только текст, иначе текст (url)
    return url.isEmpty ? text : '$text ($url)';
  });

  // Удаление жирного и курсивного текста (**текст** или __текст__)
  // (\*\*|__) - либо ** либо __ (первая группа)
  // (.*?) - содержимое (вторая группа), нежадный поиск
  // \1 - обратная ссылка на первую группу (та же последовательность)
  s = s.replaceAllMapped(RegExp(r'(\*\*|__)(.*?)\1'), (m) => m.group(2) ?? '');
  // Удаление курсива (*текст* или _текст_)
  // (\*|_) - либо * либо _ (первая группа)
  // (.*?) - содержимое (вторая группа)
  // \1 - обратная ссылка на первую группу
  s = s.replaceAllMapped(RegExp(r'(\*|_)(.*?)\1'), (m) => m.group(2) ?? '');

  // Удаление зачеркнутого текста (~~текст~~)
  // (~~) - две тильды (первая группа)
  // (.*?) - содержимое (вторая группа)
  // \1 - обратная ссылка на первую группу
  s = s.replaceAllMapped(RegExp(r'(~~)(.*?)\1'), (m) => m.group(2) ?? '');

  // Удаление заголовков (# Заголовок)
  // ^\s{0,3} - начало строки, от 0 до 3 пробелов
  // #{1,6} - от 1 до 6 символов #
  // \s* - ноль или более пробелов
  // multiLine: true - ^ и $ работают для каждой строки
  s = s.replaceAll(RegExp(r'^\s{0,3}#{1,6}\s*', multiLine: true), '');
  // Удаление цитат (> Текст)
  // ^\s{0,3} - начало строки, от 0 до 3 пробелов
  // >\s? - символ > и опциональный пробел
  s = s.replaceAll(RegExp(r'^\s{0,3}>\s?', multiLine: true), '');

  // Преобразование маркеров списков в символ •
  // ^\s* - начало строки, ноль или более пробелов
  // [-*+] - один из символов: дефис, звездочка или плюс
  // \s+ - один или более пробелов
  s = s.replaceAll(RegExp(r'^\s*[-*+]\s+', multiLine: true), '• ');
  // Преобразование нумерованных списков (1. 2. и т.д.)
  // ^\s* - начало строки, ноль или более пробелов
  // \d+ - одна или более цифр
  // \.\s+ - точка и один или более пробелов
  s = s.replaceAll(RegExp(r'^\s*\d+\.\s+', multiLine: true), '• ');

  // Сворачивание множественных пустых строк в максимум две
  // \n{3,} - три или более переноса строки подряд
  // Заменяем на два переноса строки
  s = s.replaceAll(RegExp(r'\n{3,}'), '\n\n');

  // Убираем пробелы в начале и конце и возвращаем результат
  return s.trim();
}

/// Builder для обработки LaTeX элементов в Markdown
///
/// Используется для преобразования LaTeX элементов, найденных в markdown,
/// в специальный виджет _CopyableLatex, который позволяет отображать
/// и копировать формулы.
///
/// [isUser] - флаг, указывающий является ли сообщение пользовательским
/// (влияет на стилизацию формулы)
class _CopyableLatexMarkdownBuilder extends MarkdownElementBuilder {
  /// Флаг, указывающий является ли сообщение пользовательским
  final bool isUser;

  /// Конструктор builder'а
  /// [isUser] - флаг пользовательского сообщения
  _CopyableLatexMarkdownBuilder({required this.isUser});

  /// Вызывается после обработки элемента markdown
  ///
  /// Преобразует LaTeX элемент в виджет для отображения формулы
  ///
  /// [element] - элемент markdown, содержащий LaTeX формулу
  /// [preferredStyle] - предпочтительный стиль текста (не используется)
  /// Возвращает виджет для отображения формулы или null
  @override
  Widget? visitElementAfter(md.Element element, TextStyle? preferredStyle) {
    // Получаем текстовое содержимое элемента и убираем пробелы
    final tex = element.textContent.trim();
    // Если содержимое пустое, возвращаем пустой виджет
    if (tex.isEmpty) return const SizedBox.shrink();
    // Создаем виджет для отображения LaTeX формулы
    return _CopyableLatex(tex: tex, isUser: isUser);
  }
}

/// Виджет для отображения LaTeX формулы с возможностью копирования
///
/// Отображает формулу в двух режимах:
/// - Свернутом: показывает отрендеренную формулу
/// - Развернутом: показывает исходный LaTeX код для копирования
///
/// Для блочных формул (больших) показывает карточку с кнопками управления.
/// Для инлайн формул (маленьких) показывает формулу прямо в тексте.
///
/// [tex] - строка с LaTeX формулой
/// [isUser] - флаг пользовательского сообщения (влияет на цвета)
class _CopyableLatex extends StatefulWidget {
  /// Строка с LaTeX формулой для отображения
  final String tex;

  /// Флаг, указывающий является ли сообщение пользовательским
  final bool isUser;

  /// Конструктор виджета
  /// [tex] - LaTeX формула
  /// [isUser] - флаг пользовательского сообщения
  const _CopyableLatex({required this.tex, required this.isUser});

  /// Создает состояние виджета
  @override
  State<_CopyableLatex> createState() => _CopyableLatexState();
}

/// Состояние виджета _CopyableLatex
///
/// Управляет отображением формулы (свернуто/развернуто)
/// и содержит логику для обработки и отображения LaTeX
class _CopyableLatexState extends State<_CopyableLatex> {
  /// Флаг, показывающий отображается ли исходный LaTeX код
  /// false - показывается отрендеренная формула
  /// true - показывается исходный LaTeX код для копирования
  bool _showCode = false;

  /// Очищает LaTeX формулу от обрамляющих символов
  ///
  /// Удаляет различные форматы обрамления формул:
  /// - $$...$$ (блочные формулы)
  /// - \(...\) (инлайн формулы LaTeX)
  /// - \[...\] (блочные формулы LaTeX)
  /// - $...$ (инлайн формулы)
  ///
  /// [input] - строка с формулой, возможно с обрамлением
  /// Возвращает очищенную формулу без обрамляющих символов
  String _sanitize(String input) {
    // Убираем пробелы в начале и конце
    var t = input.trim();

    // Удаляем обрамление $$...$$ (блочные формулы)
    // Проверяем что строка начинается и заканчивается на $$ и имеет минимум 4 символа
    if (t.startsWith(r'$$') && t.endsWith(r'$$') && t.length >= 4) {
      // Берем подстроку от 2 символа (после $$) до предпоследнего (перед $$)
      t = t.substring(2, t.length - 2).trim();
    }
    // Удаляем обрамление \(...\) (инлайн формулы LaTeX)
    if (t.startsWith(r'\(') && t.endsWith(r'\)') && t.length >= 4) {
      // Берем подстроку от 2 символа (после \() до предпоследнего (перед \))
      t = t.substring(2, t.length - 2).trim();
    }
    // Удаляем обрамление \[...\] (блочные формулы LaTeX)
    if (t.startsWith(r'\[') && t.endsWith(r'\]') && t.length >= 4) {
      // Берем подстроку от 2 символа (после \[) до предпоследнего (перед \])
      t = t.substring(2, t.length - 2).trim();
    }
    // Удаляем обрамление $...$ (инлайн формулы)
    if (t.startsWith(r'$') && t.endsWith(r'$') && t.length >= 2) {
      // Берем подстроку от 1 символа (после $) до предпоследнего (перед $)
      t = t.substring(1, t.length - 1).trim();
    }

    // Возвращаем очищенную формулу
    return t;
  }

  bool _isBlockLike(String t) {
    // эвристика: то, что “логичнее” показывать как блок
    if (t.contains('=')) return true;
    if (t.contains(r'\frac') || t.contains(r'\sqrt')) return true;
    if (t.length >= 18) return true;
    if (t.contains('+') ||
        t.contains('-') ||
        t.contains('*') ||
        t.contains('/')) {
      return true;
    }
    return false;
  }

  /// Строит виджет для отображения LaTeX формулы
  ///
  /// Определяет тип формулы (инлайн/блочная) и создает соответствующий UI:
  /// - Инлайн формулы отображаются прямо в тексте
  /// - Блочные формулы отображаются в карточке с кнопками управления
  ///
  /// [context] - контекст виджета для доступа к теме и другим ресурсам
  /// Возвращает виджет для отображения формулы
  @override
  Widget build(BuildContext context) {
    // Функция для переключения между отображением формулы и исходного кода
    void toggle() => setState(() => _showCode = !_showCode);

    // Получаем цветовую схему из темы приложения
    final scheme = Theme.of(context).colorScheme;

    // Очищаем формулу от обрамляющих символов ($$, $, \(, \[ и т.д.)
    final raw = _sanitize(widget.tex);
    // Нормализуем строку (убираем специальные пробелы и символы)
    final t = _normalize(raw);

    // Создаем стиль текста в зависимости от типа сообщения (пользователь/ассистент)
    final textStyle = TextStyle(
      // Цвет текста: для пользователя - цвет на primary, для ассистента - цвет на surface
      color: widget.isUser ? scheme.onPrimary : scheme.onSurface,
      // Размер шрифта
      fontSize: 14,
      // Высота строки (межстрочный интервал)
      height: 1.25,
    );

    // Одиночные символы (буквы, цифры) не считаем формулой - показываем как обычный текст
    if (_isSinglePlainSymbol(t)) {
      return Text(t, style: textStyle);
    }

    // Проверяем, выглядит ли строка как математическая формула для рендеринга
    final isMath = _looksRenderableAsMath(t);
    // Если это не математика - показываем как обычный текст
    if (!isMath) {
      return Text(t, style: textStyle);
    }

    // Определяем, должна ли формула отображаться как блочная
    final blockLike = _isBlockLike(t);

    // INLINE: без карточек/кнопок — чтобы не ломать поток текста
    if (!blockLike) {
      return Math.tex(
        t,
        mathStyle: MathStyle.text,
        textStyle: textStyle,
        onErrorFallback: (e) => Text(t, style: textStyle),
      );
    }

    // BLOCK: карточка как “кодовый блок” + кнопки +/−
    final cardBg = widget.isUser
        ? scheme.onPrimary.withValues(alpha: 0.10)
        : scheme.surfaceContainerHighest.withValues(alpha: 0.85);

    return Container(
      margin: const EdgeInsets.only(top: 6, bottom: 6),
      padding: const EdgeInsets.all(10),
      decoration: BoxDecoration(
        color: cardBg,
        borderRadius: BorderRadius.circular(14),
        border: Border.all(color: scheme.outlineVariant),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // верхняя панель: +/− и (при раскрытии) copy
          Row(
            children: [
              Expanded(
                child: Text(
                  'Формула',
                  style: TextStyle(
                    color: widget.isUser
                        ? scheme.onPrimary
                        : scheme.onSurfaceVariant,
                    fontWeight: FontWeight.w700,
                    fontSize: 12,
                  ),
                ),
              ),
              IconButton(
                visualDensity: VisualDensity.compact,
                padding: const EdgeInsets.all(4),
                constraints: const BoxConstraints(minWidth: 28, minHeight: 28),
                tooltip: _showCode ? 'Свернуть' : 'Показать LaTeX',
                icon: Icon(_showCode ? Icons.remove : Icons.add, size: 18),
                onPressed: toggle,
              ),
              if (_showCode)
                IconButton(
                  visualDensity: VisualDensity.compact,
                  padding: const EdgeInsets.all(4),
                  constraints:
                      const BoxConstraints(minWidth: 28, minHeight: 28),
                  tooltip: 'Копировать LaTeX',
                  icon: const Icon(Icons.copy, size: 18),
                  onPressed: () async {
                    await Clipboard.setData(ClipboardData(text: t));
                    if (!context.mounted) return;
                    TopToast.show(
                      context,
                      'LaTeX скопирован',
                      type: TopToastType.success,
                      duration: const Duration(seconds: 1),
                    );
                  },
                ),
            ],
          ),

          const SizedBox(height: 8),

          // содержимое: либо рендер, либо “кодовый блок”
          if (!_showCode)
            SingleChildScrollView(
              scrollDirection: Axis.horizontal,
              child: Math.tex(
                t,
                mathStyle: MathStyle.display,
                textStyle: textStyle,
                onErrorFallback: (e) => Text(t, style: textStyle),
              ),
            )
          else
            Container(
              width: double.infinity,
              padding: const EdgeInsets.all(10),
              decoration: BoxDecoration(
                color: scheme.surface.withValues(alpha: 0.35),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: scheme.outlineVariant),
              ),
              child: SelectableText(
                t,
                style: TextStyle(
                  fontFamily: 'monospace',
                  fontSize: 13,
                  height: 1.35,
                  color: widget.isUser ? scheme.onPrimary : scheme.onSurface,
                ),
              ),
            ),
        ],
      ),
    );
  }
}

/// Нормализует строку, удаляя специальные пробелы и символы
///
/// Удаляет:
/// - Zero-width space (\u200B) - невидимый пробел
/// - BOM (\uFEFF) - маркер порядка байтов
/// - Non-breaking space (\u00A0) - заменяет на обычный пробел
///
/// [s] - входная строка
/// Возвращает нормализованную строку без специальных символов
String _normalize(String s) {
  return s
      // Удаляем zero-width space (невидимый пробел, может мешать рендерингу)
      .replaceAll('\u200B', '') // zero width space
      // Удаляем BOM (маркер порядка байтов, может появляться при копировании)
      .replaceAll('\uFEFF', '') // BOM
      // Заменяем non-breaking space на обычный пробел
      .replaceAll('\u00A0', ' ') // nbsp
      // Убираем пробелы в начале и конце
      .trim();
}

bool _looksRenderableAsMath(String t) {
  if (t.isEmpty) return false;

  // если строка состоит только из операторов/скобок/пробелов — это не математика для TeX
  final onlyOps = RegExp(r'^[\s=+\-*/<>.,:;(){}\[\]]+$').hasMatch(t);
  if (onlyOps) return false;

  // должна быть хотя бы “математическая сущность”: буквы/цифры/слеши/степени/индексы/команды
  final hasSignal = RegExp(r'[A-Za-zА-Яа-я0-9\\^_{}]').hasMatch(t);
  return hasSignal;
}

/// Проверяет, является ли строка одиночным простым символом
///
/// Одиночные символы (буквы, цифры) не считаются формулами
/// и отображаются как обычный текст.
///
/// [t] - строка для проверки
/// Возвращает true если строка состоит из одного символа (буква или цифра)
bool _isSinglePlainSymbol(String t) {
  // Нормализуем строку (убираем специальные символы)
  final s = _normalize(t);

  // Проверяем, что строка состоит ровно из одного символа
  // который является буквой (латиница или кириллица) или цифрой
  // Регулярное выражение: ^ - начало, [...] - класс символов, $ - конец
  return RegExp(r'^[A-Za-zА-Яа-я0-9]$').hasMatch(s);
}

// --- AUTO LaTeXIFY (автоматическое преобразование Unicode математики в LaTeX) ---
// Превращаем Unicode символы в LaTeX: c² -> c^{2}, √100 -> \sqrt{100}, и оборачиваем в $...$

/// Карта для преобразования надстрочных символов (степени) в обычные цифры
///
/// Используется для преобразования Unicode надстрочных символов (⁰, ¹, ², и т.д.)
/// в обычные цифры для LaTeX синтаксиса
const Map<String, String> _supMap = {
  '⁰': '0', // Надстрочный ноль
  '¹': '1', // Надстрочная единица
  '²': '2', // Надстрочная двойка
  '³': '3', // Надстрочная тройка
  '⁴': '4', // Надстрочная четверка
  '⁵': '5', // Надстрочная пятерка
  '⁶': '6', // Надстрочная шестерка
  '⁷': '7', // Надстрочная семерка
  '⁸': '8', // Надстрочная восьмерка
  '⁹': '9', // Надстрочная девятка
};

/// Карта для преобразования подстрочных символов (индексы) в обычные цифры
///
/// Используется для преобразования Unicode подстрочных символов (₀, ₁, ₂, и т.д.)
/// в обычные цифры для LaTeX синтаксиса
const Map<String, String> _subMap = {
  '₀': '0', // Подстрочный ноль
  '₁': '1', // Подстрочная единица
  '₂': '2', // Подстрочная двойка
  '₃': '3', // Подстрочная тройка
  '₄': '4', // Подстрочная четверка
  '₅': '5', // Подстрочная пятерка
  '₆': '6', // Подстрочная шестерка
  '₇': '7', // Подстрочная семерка
  '₈': '8', // Подстрочная восьмерка
  '₉': '9', // Подстрочная девятка
};

/// Преобразует надстрочные Unicode символы в обычные цифры
///
/// Пример: "²³" -> "23"
///
/// [s] - строка с надстрочными символами
/// Возвращает строку с обычными цифрами
String _supToNormal(String s) => s.split('').map((c) => _supMap[c] ?? c).join();

/// Преобразует подстрочные Unicode символы в обычные цифры
///
/// Пример: "₁₂" -> "12"
///
/// [s] - строка с подстрочными символами
/// Возвращает строку с обычными цифрами
String _subToNormal(String s) => s.split('').map((c) => _subMap[c] ?? c).join();

/// Преобразует Unicode математические символы в LaTeX синтаксис
///
/// Выполняет следующие преобразования:
/// - √100 -> \sqrt{100} (квадратный корень)
/// - x² -> x^{2} (степени)
/// - x₁ -> x_{1} (индексы)
///
/// [line] - строка с Unicode математическими символами
/// Возвращает строку с LaTeX синтаксисом
String _unicodeMathToTex(String line) {
  // Копируем входную строку для обработки
  var t = line;

  // Преобразование квадратного корня: √100 -> \sqrt{100}
  // Регулярное выражение: √ - символ корня, \s* - ноль или более пробелов,
  // ([0-9]+) - одна или более цифр (группа 1)
  t = t.replaceAllMapped(RegExp(r'√\s*([0-9]+)'), (m) {
    // Заменяем на LaTeX команду \sqrt{число}
    return r'\sqrt{${m.group(1) ?? ' '}}';
  });

  // Преобразование степеней: x², a⁵⁶ -> x^{2}, a^{56}
  // Регулярное выражение:
  // ([A-Za-zА-Яа-я0-9\)\]\}]) - буква, цифра или закрывающая скобка (группа 1)
  // ([⁰¹²³⁴⁵⁶⁷⁸⁹]+) - один или более надстрочных символов (группа 2)
  t = t.replaceAllMapped(
    RegExp(r'([A-Za-zА-Яа-я0-9\)\]\}])([⁰¹²³⁴⁵⁶⁷⁸⁹]+)'),
    // Заменяем на LaTeX синтаксис: символ^{степень}
    (m) => '${m.group(1)}^{${_supToNormal(m.group(2) ?? '')}}',
  );

  // Преобразование индексов: x₁, a₁₂ -> x_{1}, a_{12}
  // Регулярное выражение:
  // ([A-Za-zА-Яа-я0-9\)\]\}]) - буква, цифра или закрывающая скобка (группа 1)
  // ([₀₁₂₃₄₅₆₇₈₉]+) - один или более подстрочных символов (группа 2)
  t = t.replaceAllMapped(
    RegExp(r'([A-Za-zА-Яа-я0-9\)\]\}])([₀₁₂₃₄₅₆₇₈₉]+)'),
    // Заменяем на LaTeX синтаксис: символ_{индекс}
    (m) => '${m.group(1)}_{${_subToNormal(m.group(2) ?? '')}}',
  );

  // Возвращаем преобразованную строку
  return t;
}

bool _shouldWrapAsLatex(String tex) {
  final t = _normalize(tex);
  if (t.isEmpty) return false;
  if (_isSinglePlainSymbol(t)) return false;

  // Уже есть LaTeX-обвязка — не трогаем
  if (t.contains(r'$') || t.contains(r'\(') || t.contains(r'\[')) return false;

  // Если в строке есть нормальные русские слова — это не “чистая формула”
  // (чтобы "Пример: катеты a=..." не превращался целиком в Math)
  if (RegExp(r'[А-Яа-я]{3,}').hasMatch(t)) return false;

  final hasOps = RegExp(r'[=+\-*/<>]').hasMatch(t);
  final hasLettersDigits = RegExp(r'[A-Za-z0-9]').hasMatch(t);
  final hasTeXSignal = RegExp(r'[\\^_{}]').hasMatch(t) || t.contains(r'\sqrt');

  return hasOps && hasLettersDigits && hasTeXSignal;
}

/// Автоматически преобразует Markdown текст, добавляя LaTeX разметку для формул
///
/// Проходит по тексту и автоматически оборачивает математические выражения
/// в LaTeX разметку ($$...$$). Не трогает блоки кода (```...```).
///
/// Алгоритм:
/// 1. Находит все блоки кода и пропускает их
/// 2. Для остального текста проверяет каждую строку
/// 3. Если строка выглядит как формула - оборачивает в $$
/// 4. Преобразует Unicode математику (², √ и т.д.) в LaTeX
///
/// [input] - входной Markdown текст
/// Возвращает Markdown текст с автоматически добавленной LaTeX разметкой
String _autoLatexifyMarkdown(String input) {
  // Регулярное выражение для поиска блоков кода (```...```)
  // НЕ трогаем code fences - они остаются как есть
  // Регулярное выражение: ``` - три обратных кавычки, [\s\S]*? - любое содержимое (нежадный), ``` - закрывающие
  final reFence = RegExp(r'```[\s\S]*?```');
  // Буфер для накопления результата
  final out = StringBuffer();
  // Позиция последнего обработанного символа
  var last = 0;

  /// Обрабатывает обычный текст (не код)
  ///
  /// Проверяет каждую строку и оборачивает формулы в LaTeX разметку
  ///
  /// [chunk] - фрагмент текста для обработки
  void processPlain(String chunk) {
    // Разбиваем текст на строки
    final lines = chunk.split('\n');
    // Проходим по каждой строке
    for (var i = 0; i < lines.length; i++) {
      final line = lines[i];

      // Если в строке уже есть LaTeX разметка ($...$, \(...\), \[...\])
      // оставляем строку как есть (не обрабатываем повторно)
      if (line.contains(r'$') || line.contains(r'\(') || line.contains(r'\[')) {
        // Записываем строку без изменений
        out.writeln(line);
        // Переходим к следующей строке
        continue;
      }

      // Преобразуем Unicode математику в LaTeX (² -> ^{2}, √ -> \sqrt и т.д.)
      final tex = _unicodeMathToTex(line);
      // Проверяем, нужно ли обернуть строку в LaTeX разметку
      if (_shouldWrapAsLatex(tex)) {
        // Оборачиваем формулу в блочную LaTeX разметку ($$...$$)
        out.writeln(r'$$');
        // Записываем саму формулу (убираем пробелы в начале/конце)
        out.writeln(tex.trim());
        // Закрывающая разметка
        out.writeln(r'$$');
      } else {
        // Если это не формула - записываем строку без изменений
        out.writeln(line);
      }
    }
  }

  // Обрабатываем входной текст, пропуская блоки кода
  // Находим все совпадения блоков кода
  for (final m in reFence.allMatches(input)) {
    // Обрабатываем текст до начала блока кода
    processPlain(input.substring(last, m.start));
    // Записываем сам блок кода без изменений
    out.write(m.group(0)); // code block как есть
    // Обновляем позицию последнего обработанного символа
    last = m.end;
  }
  // Обрабатываем оставшийся текст после последнего блока кода
  processPlain(input.substring(last));

  // Возвращаем результат, убирая пробелы справа
  return out.toString().trimRight();
}

