// MessageExt - расширения для модели ChatMessage
//
// Добавляет утилитные методы для работы с сообщениями:
// - cleanContent: очистка контента от мусорных символов и нормализация

import 'message.dart';

/// Расширение для ChatMessage с утилитными методами
extension ChatMessageCleanContent on ChatMessage {
  /// Возвращает очищенный контент, безопасный для рендера/копирования
  /// 
  /// Выполняет:
  /// - Удаление нулевых байтов (\u0000) - иногда прилетают от провайдера/БД
  /// - Удаление BOM (\ufeff) - может быть в начале текста
  /// - Нормализация переводов строк (унификация под \n для markdown)
  /// 
  /// Используется:
  /// - При отображении сообщений в UI
  /// - При копировании текста в буфер обмена
  String get cleanContent {
    var s = content;

    // иногда прилетает мусор от провайдера/БД
    s = s.replaceAll('\u0000', '');
    s = s.replaceAll('\ufeff', '');

    // унифицируем переносы строк под markdown
    s = s.replaceAll('\r\n', '\n').replaceAll('\r', '\n');

    return s;
  }
}
